#!/usr/bin/env node
/**
 * Recomputes the "N fixes landed upstream" headline in README.md and writes
 * data/upstream-stats.json. Runs daily from .github/workflows/upstream-count.yml
 * and can be run by hand: GH_TOKEN=<token> node scripts/upstream-count.mjs
 *
 * Source is the GitHub search index — the same source the shields.io badges in
 * README.md read. The list-pull-requests REST endpoint is not usable here: it
 * silently ignores `creator=`. Definition and exclusions: MAINTAINING.md.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const LOGIN = 'santhiprakash';
/** Repositories owned by these accounts are not "other people's projects". */
const EXCLUDED_OWNERS = ['santhiprakash', 'minervainfo', 'minervainfoedtech', 'santhiprakashb'];
const MONTHS_KEPT = 6;
const TOP_REPOS_KEPT = 10;
const LATEST_KEPT = 3;
const MAX_ATTEMPTS = 4;
const MAX_RATE_LIMIT_WAIT_MS = 10 * 60_000;
const DAY_MS = 24 * 60 * 60_000;

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const README_PATH = join(ROOT, 'README.md');
const DATA_PATH = join(ROOT, 'data', 'upstream-stats.json');
const TOKEN = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;

const HEADLINE_PATTERN = /^## (\d+) fixes landed upstream$/m;
const COUNTED_PATTERN = /^Merged into other people's projects, counted \d{1,2} \w{3} \d{4}\.$/m;

/** Authorship disclosures an upstream pull request body can carry. */
const AI_STATEMENT_PATTERN =
  /\bAI-assisted\b|AI disclosure:|with AI assistance|\*\*AI:\*\*|Generated by Grok|CURSOR_AGENT_PR_BODY_BEGIN|Made with \[Cursor\]|\[x\] Yes, AI helped generate|\[x\] Mostly or partially generated by an AI agent/;
const NAMED_TOOL_PATTERNS = [
  ['Cursor', /CURSOR_AGENT_PR_BODY_BEGIN|Made with \[Cursor\]/],
  ['Grok', /Generated by Grok|\*\*AI:\*\*[^\n]*Grok/i],
  ['Devin', /\*\*AI:\*\*[^\n]*Devin/i],
];

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const round1 = (value) => Math.round(value * 10) / 10;
const repoOf = (item) => item.repository_url.split('/repos/')[1];
const ownerOf = (item) => repoOf(item).split('/')[0];
const isUpstream = (item) => !EXCLUDED_OWNERS.includes(ownerOf(item));

async function githubJson(path, query = {}) {
  const url = new URL(`https://api.github.com${path}`);
  for (const [key, value] of Object.entries(query)) url.searchParams.set(key, value);

  for (let attempt = 0; ; attempt += 1) {
    let response;
    try {
      response = await fetch(url, {
        headers: {
          accept: 'application/vnd.github+json',
          authorization: `Bearer ${TOKEN}`,
          'user-agent': 'upstream-count',
        },
        signal: AbortSignal.timeout(30_000),
      });
    } catch (error) {
      if (attempt >= MAX_ATTEMPTS) throw error;
      await sleep(2_000 * 2 ** attempt);
      continue;
    }

    // 403/429: either the hourly search window (x-ratelimit-reset) or a secondary limit (retry-after).
    if (response.status === 403 || response.status === 429) {
      const resetAt = Number(response.headers.get('x-ratelimit-reset')) * 1000;
      const retryAfter = Number(response.headers.get('retry-after'));
      const waitMs = retryAfter
        ? retryAfter * 1000
        : resetAt
          ? resetAt - Date.now() + 1_000
          : 60_000;
      if (attempt >= MAX_ATTEMPTS || waitMs > MAX_RATE_LIMIT_WAIT_MS) {
        throw new Error(`Rate limited; next window in ${Math.round(waitMs / 1000)}s`);
      }
      await sleep(Math.max(waitMs, 1_000));
      continue;
    }

    if (!response.ok) throw new Error(`GitHub ${response.status} for ${url.pathname}${url.search}`);
    return response.json();
  }
}

const searchCount = async (query) => {
  const result = await githubJson('/search/issues', { q: query, per_page: 1 });
  await sleep(1_500);
  return result.total_count;
};

async function searchAll(query) {
  const items = [];
  for (let page = 1; ; page += 1) {
    const result = await githubJson('/search/issues', {
      q: query,
      per_page: 100,
      page,
      sort: 'created',
      order: 'asc',
    });
    items.push(...result.items);
    await sleep(1_500);
    if (result.items.length === 0 || items.length >= result.total_count) return items;
  }
}

async function collectStats() {
  const excluded = EXCLUDED_OWNERS.map((owner) => `-user:${owner}`).join(' ');
  const merged = await searchAll(`author:${LOGIN} is:pr is:merged`);
  const upstream = merged.filter(isUpstream);
  const submitted = await searchCount(`author:${LOGIN} is:pr ${excluded}`);
  const open = await searchCount(`author:${LOGIN} is:pr is:open ${excluded}`);

  const now = Date.now();
  const perMonth = new Map();
  const perRepo = new Map();
  let last30Days = 0;
  for (const item of upstream) {
    const month = item.closed_at.slice(0, 7);
    const repo = repoOf(item);
    perMonth.set(month, (perMonth.get(month) ?? 0) + 1);
    perRepo.set(repo, (perRepo.get(repo) ?? 0) + 1);
    if (Date.parse(item.closed_at) >= now - 30 * DAY_MS) last30Days += 1;
  }

  const byRank = (a, b) => b[1] - a[1] || a[0].localeCompare(b[0]);
  const bodies = upstream.map((item) => item.body ?? '');

  return {
    login: LOGIN,
    excluded_owners: EXCLUDED_OWNERS,
    // Counts cover public upstream pull requests only: that is all a visitor can
    // see, and all the workflow's GITHUB_TOKEN can see (no private-repo access).
    upstream: {
      merged: upstream.length,
      repos: perRepo.size,
      submitted,
      open,
      merge_rate_pct: submitted ? round1((100 * upstream.length) / submitted) : null,
      last_30_days: last30Days,
      by_month: [...perMonth]
        .sort((a, b) => a[0].localeCompare(b[0]))
        .slice(-MONTHS_KEPT)
        .map(([month, merged]) => ({ month, merged })),
      top_repos: [...perRepo]
        .sort(byRank)
        .slice(0, TOP_REPOS_KEPT)
        .map(([repo, merged]) => ({ repo, merged })),
      latest: upstream
        .toSorted((a, b) => b.closed_at.localeCompare(a.closed_at))
        .slice(0, LATEST_KEPT)
        .map((item) => ({
          repo: repoOf(item),
          number: item.number,
          title: item.title,
          url: item.html_url,
          merged_at: item.closed_at.slice(0, 10),
        })),
    },
    ai_disclosure: {
      states_assistance: bodies.filter((body) => AI_STATEMENT_PATTERN.test(body)).length,
      named_tool: Object.fromEntries(
        NAMED_TOOL_PATTERNS.map(([name, pattern]) => [name, bodies.filter((body) => pattern.test(body)).length]),
      ),
    },
  };
}

async function refreshHeadline(upstreamMerged) {
  const readme = await readFile(README_PATH, 'utf8');
  const headline = readme.match(HEADLINE_PATTERN);
  if (!headline) throw new Error('Headline "## N fixes landed upstream" not found in README.md');

  const current = Number(headline[1]);
  if (current === upstreamMerged) return { current, changed: false };

  const counted = new Intl.DateTimeFormat('en-GB', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'Asia/Kolkata',
  }).format(new Date());
  const next = readme
    .replace(HEADLINE_PATTERN, `## ${upstreamMerged} fixes landed upstream`)
    .replace(COUNTED_PATTERN, `Merged into other people's projects, counted ${counted}.`);
  if (!COUNTED_PATTERN.test(next)) throw new Error('"counted <date>" line not found in README.md');

  await writeFile(README_PATH, next);
  return { current, changed: true };
}

async function writeStats(stats) {
  await mkdir(dirname(DATA_PATH), { recursive: true });
  const json = `${JSON.stringify(stats, null, 2)}\n`;
  const previous = await readFile(DATA_PATH, 'utf8').catch(() => '');
  if (json === previous) return false;
  await writeFile(DATA_PATH, json);
  return true;
}

async function main() {
  if (!TOKEN) throw new Error('GH_TOKEN is not set');
  const stats = await collectStats();
  const headline = await refreshHeadline(stats.upstream.merged);
  const statsWritten = await writeStats(stats);

  const { upstream } = stats;
  console.log(
    `upstream merged=${upstream.merged} repos=${upstream.repos} submitted=${upstream.submitted} ` +
      `open=${upstream.open} last30d=${upstream.last_30_days} | ` +
      (headline.changed
        ? `headline ${headline.current} -> ${upstream.merged}`
        : `headline unchanged (${headline.current})`) +
      ` | stats ${statsWritten ? 'written' : 'unchanged'}`,
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
